# DR PDF
# ============================================================
def make_dr_pdf(dr, pr, base_url):
    buf = io.BytesIO()
    doc = SimpleDocTemplate(
        buf, pagesize=A4,
        leftMargin=20 * mm, rightMargin=20 * mm,
        topMargin=15 * mm, bottomMargin=20 * mm,
        title=f"{dr.number} — Delivery Receipt",
    )
    story = []
    styles = getSampleStyleSheet()

    _header(story, f"Delivery Receipt {dr.number}",
            "Procurement Requisition & Fulfilment System")

    received_at = _eat(dr.received_at).strftime("%d/%m/%Y %H:%M") if dr.received_at else "—"
    receiver = dr.received_by_user.name if getattr(dr, "received_by_user", None) else "—"

    story.append(_kv_table([
        ("Against PR",      pr.number or "—"),
        ("Site",            f"{pr.site.name} ({pr.site.code})"),
        ("Received by",     receiver),
        ("Date received",   received_at),
        ("Delivery note",   dr.delivery_note_ref or "—"),
        ("Notes",           dr.notes or "—"),
    ]))
    story.append(Spacer(1, 8 * mm))

    story.append(Paragraph(
        '<font color="#2B2B2B" size="12"><b>Items received</b></font>',
        styles["Normal"]))
    story.append(Spacer(1, 3 * mm))

    headers = ["Code", "Item", "Unit", "Received", "Rejected", "Note"]
    rows = []
    for drl in dr.lines:
        line = drl.pr_line
        note = ""
        if drl.qty_rejected and float(drl.qty_rejected or 0) > 0:
            note = drl.reject_reason or "damaged/wrong"
        rows.append([
            line.item.code if line and line.item else "—",
            line.item.name if line and line.item else "—",
            line.item.unit.symbol if line and line.item and line.item.unit else "",
            f"{float(drl.qty_received or 0):g}",
            f"{float(drl.qty_rejected or 0):g}" if drl.qty_rejected else "—",
            note or "—",
        ])
    if not rows:
        rows = [["—", "No lines", "", "", "", ""]]

        story.append(_lines_table(
        headers, rows,
        col_widths=[22 * mm, 80 * mm, 15 * mm, 20 * mm, 20 * mm, 33 * mm]))
    story.append(Spacer(1, 15 * mm))

    sig = Table(
        [["Received by (Site)", "Witness / Checked by"],
         ["\n\n__________________________", "\n\n__________________________"]],
        colWidths=[85 * mm, 85 * mm],
    )
    sig.setStyle(TableStyle([
        ("TEXTCOLOR", (0, 0), (-1, 0), STONE),
        ("FONTSIZE", (0, 0), (-1, -1), 9),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("LEFTPADDING", (0, 0), (-1, -1), 0),
    ]))
    story.append(sig)

    story.append(Spacer(1, 10 * mm))
    story.append(HRFlowable(width="100%", color=BORDER))
    story.append(Spacer(1, 3 * mm))
    story.append(Paragraph(
        f'<font color="#6B665B" size="8">'
        f'This Delivery Receipt is immutable. Corrections require a documented '
        f'adjustment by the Procurement Officer. Open in system: {base_url}'
        f'</font>', styles["Normal"]))

    doc.build(story, onFirstPage=_footer, onLaterPages=_footer)
    buf.seek(0)
    return buf


