"""
pdf_maker.py — Generate branded PDFs for PRs, DRs and registers.
Uses ReportLab. Colours match the app theme: Charcoal #2B2B2B, Gold #B8860B.
All timestamps displayed in EAT (UTC+3).
"""
import io
from datetime import datetime, timedelta
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import (SimpleDocTemplate, Paragraph, Spacer, Table,
                                TableStyle, HRFlowable)


CHARCOAL = colors.HexColor("#2B2B2B")
GOLD     = colors.HexColor("#B8860B")
STONE    = colors.HexColor("#6B665B")
BORDER   = colors.HexColor("#D9D2C3")
BG       = colors.HexColor("#FAF8F3")


def _eat(dt):
    """Convert naive UTC datetime to EAT (UTC+3)."""
    return (dt + timedelta(hours=3)) if dt else None


def _brand_text():
    try:
        from models import SystemSetting
        row = SystemSetting.query.filter_by(key="company_logo_text").first()
        return row.value if row and row.value else "PRFS"
    except Exception:
        return "PRFS"


# ============================================================
# HEADER / FOOTER
# ============================================================
def _header(story, title, subtitle):
    styles = getSampleStyleSheet()
    brand = _brand_text()

    banner = Table(
        [[Paragraph(
            f'<font color="#B8860B" size="22"><b>{brand}</b></font><br/>'
            f'<font color="#EEEEEE" size="9">{subtitle}</font>',
            styles["Normal"])]],
        colWidths=[170 * mm],
        rowHeights=[22 * mm],
    )
    banner.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), CHARCOAL),
        ("LEFTPADDING", (0, 0), (-1, -1), 12),
        ("TOPPADDING", (0, 0), (-1, -1), 6),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
    ]))
    story.append(banner)
    story.append(Spacer(1, 6 * mm))

    story.append(Paragraph(
        f'<font color="#B8860B" size="16"><b>{title}</b></font>',
        styles["Normal"]))
    story.append(Spacer(1, 4 * mm))


def _footer(canvas, doc):
    canvas.saveState()
    canvas.setFont("Helvetica", 8)
    canvas.setFillColor(STONE)
    ts = (datetime.utcnow() + timedelta(hours=3)).strftime("%d/%m/%Y %H:%M")
    canvas.drawString(20 * mm, 12 * mm, f"Generated by PRFS · {ts} EAT")
    canvas.drawRightString(190 * mm, 12 * mm, f"Page {doc.page}")
    canvas.setStrokeColor(BORDER)
    canvas.setLineWidth(0.4)
    canvas.line(20 * mm, 15 * mm, 190 * mm, 15 * mm)
    canvas.restoreState()


def _kv_table(pairs):
    styles = getSampleStyleSheet()
    data = [[Paragraph(f'<font color="#6B665B">{k}</font>', styles["Normal"]),
             Paragraph(f'<b>{v or "—"}</b>', styles["Normal"])]
            for k, v in pairs]
    t = Table(data, colWidths=[45 * mm, 125 * mm])
    t.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("TOPPADDING", (0, 0), (-1, -1), 2),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 2),
        ("LEFTPADDING", (0, 0), (-1, -1), 0),
    ]))
    return t


def _lines_table(headers, rows, col_widths):
    styles = getSampleStyleSheet()
    data = [[Paragraph(f'<b>{h}</b>', styles["Normal"]) for h in headers]]
    for r in rows:
        data.append([Paragraph(str(c) if c is not None else "", styles["Normal"])
                     for c in r])

    t = Table(data, colWidths=col_widths, repeatRows=1)
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), GOLD),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 9),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("TOPPADDING", (0, 0), (-1, -1), 6),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
        ("LEFTPADDING", (0, 0), (-1, -1), 6),
        ("RIGHTPADDING", (0, 0), (-1, -1), 6),
        ("LINEBELOW", (0, 0), (-1, 0), 0.8, CHARCOAL),
        ("LINEBELOW", (0, 1), (-1, -1), 0.3, BORDER),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, BG]),
    ]))
    return t


# ============================================================
# PR PDF
# ============================================================
def make_pr_pdf(pr, base_url):
    buf = io.BytesIO()
    doc = SimpleDocTemplate(
        buf, pagesize=A4,
        leftMargin=20 * mm, rightMargin=20 * mm,
        topMargin=15 * mm, bottomMargin=20 * mm,
        title=f"{pr.number} — Purchase Requisition",
    )
    story = []
    styles = getSampleStyleSheet()

    _header(story, f"Purchase Requisition {pr.number or '(draft)'}",
            "Procurement Requisition & Fulfilment System")

    submitted = _eat(pr.submitted_at).strftime("%d/%m/%Y %H:%M") if pr.submitted_at else "—"
    story.append(_kv_table([
        ("Site",        f"{pr.site.name} ({pr.site.code})"),
        ("Requester",   pr.requester.name),
        ("Status",      pr.status),
        ("Priority",    pr.priority),
        ("Required by", pr.required_by.strftime("%d/%m/%Y") if pr.required_by else "—"),
        ("Submitted",   submitted),
        ("Purpose",     pr.purpose or "—"),
        ("Notes",       pr.notes or "—"),
    ]))
    story.append(Spacer(1, 8 * mm))

    story.append(Paragraph(
        '<font color="#2B2B2B" size="12"><b>Lines</b></font>',
        styles["Normal"]))
    story.append(Spacer(1, 3 * mm))

    headers = ["Code", "Item", "Unit", "Req.", "Ord.", "Rec.", "Outst.", "Status"]
    rows = []
    for l in pr.lines:
        rows.append([
            l.item.code,
            l.item.name,
            l.item.unit.symbol if l.item.unit else "",
            f"{float(l.requested_qty or 0):g}",
            f"{float(l.ordered_qty or 0):g}",
            f"{float(l.received_qty or 0):g}",
            f"{l.outstanding_qty:g}",
            l.status,
        ])
    if not rows:
        rows = [["—", "No lines", "", "", "", "", "", ""]]

    story.append(_lines_table(
        headers, rows,
        col_widths=[22 * mm, 55 * mm, 12 * mm, 15 * mm,
                    15 * mm, 15 * mm, 15 * mm, 21 * mm]))
    story.append(Spacer(1, 8 * mm))

    try:
        comments = getattr(pr, 'comments', None)
        if comments:
            story.append(Spacer(1, 8 * mm))
            story.append(Paragraph(
                '<font color="#2B2B2B" size="12"><b>Discussion</b></font>',
                styles["Normal"]))
            story.append(Spacer(1, 3 * mm))
            comment_rows = []
            for c in comments:
                author = c.author.name if c.author else "—"
                role = c.author.role if c.author else ""
                when = _eat(c.at).strftime("%d/%m/%Y %H:%M") if c.at else ""
                comment_rows.append([
                    Paragraph(f'<b>{author}</b> ({role})<br/>'
                              f'<font size="7" color="#6B665B">{when}</font>',
                              styles["Normal"]),
                    Paragraph(c.text, styles["Normal"]),
                ])
            t = Table(comment_rows, colWidths=[45 * mm, 125 * mm])
            t.setStyle(TableStyle([
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("TOPPADDING", (0, 0), (-1, -1), 6),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
                ("LEFTPADDING", (0, 0), (-1, -1), 4),
                ("LINEBELOW", (0, 0), (-1, -2), 0.3, BORDER),
            ]))
            story.append(t)
    except Exception:
        pass

    try:
        atts = getattr(pr, 'attachments', None)
        if atts:
            live = [a for a in atts if not a.deleted]
            if live:
                story.append(Spacer(1, 8 * mm))
                story.append(Paragraph(
                    '<font color="#2B2B2B" size="12"><b>Attachments</b></font>',
                    styles["Normal"]))
                story.append(Spacer(1, 2 * mm))
                for a in live:
                    size_kb = (a.size or 0) / 1024
                    story.append(Paragraph(
                        f'• {a.filename} '
                        f'<font color="#6B665B">({size_kb:.0f} KB, '
                        f'{a.uploader.name if a.uploader else "—"} · '
                        f'{_eat(a.uploaded_at).strftime("%d/%m/%Y") if a.uploaded_at else "—"})</font>',
                        styles["Normal"]))
    except Exception:
        pass

    story.append(Spacer(1, 8 * mm))
    story.append(HRFlowable(width="100%", color=BORDER))
    story.append(Spacer(1, 3 * mm))
    story.append(Paragraph(
        f'<font color="#6B665B" size="8">Open in system: {base_url}</font>',
        styles["Normal"]))

    doc.build(story, onFirstPage=_footer, onLaterPages=_footer)
    buf.seek(0)
    return buf


