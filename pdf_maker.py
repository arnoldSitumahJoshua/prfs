# REGISTER PDF
# ============================================================
def make_register_pdf(title, subtitle, headers, rows, col_widths=None):
    buf = io.BytesIO()
    doc = SimpleDocTemplate(
        buf, pagesize=A4,
        leftMargin=15 * mm, rightMargin=15 * mm,
        topMargin=15 * mm, bottomMargin=20 * mm,
        title=title,
    )
    story = []
    styles = getSampleStyleSheet()

    brand = _brand_text()
    banner = Table(
        [[Paragraph(
            f'<font color="#B8860B" size="22"><b>{brand}</b></font><br/>'
            f'<font color="#EEEEEE" size="9">{subtitle}</font>',
            styles["Normal"])]],
        colWidths=[180 * mm],
        rowHeights=[20 * mm],
    )
    banner.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), CHARCOAL),
        ("LEFTPADDING", (0, 0), (-1, -1), 12),
        ("TOPPADDING", (0, 0), (-1, -1), 6),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
    ]))
    story.append(banner)
    story.append(Spacer(1, 6 * mm))

    story.append(Paragraph(
        f'<font color="#B8860B" size="16"><b>{title}</b></font>',
        styles["Normal"]))
    story.append(Spacer(1, 2 * mm))

    ts = (datetime.utcnow() + timedelta(hours=3)).strftime("%d/%m/%Y %H:%M")
    story.append(Paragraph(
        f'<font color="#6B665B" size="9">'
        f'Generated on {ts} EAT · {len(rows)} record{"" if len(rows) == 1 else "s"}'
        f'</font>', styles["Normal"]))
    story.append(Spacer(1, 6 * mm))

    if not rows:
        story.append(Paragraph('<i>No records to display.</i>', styles["Normal"]))
    else:
        data = [[Paragraph(f'<b>{h}</b>', styles["Normal"]) for h in headers]]
        for r in rows:
            data.append([
                Paragraph(str(c) if c is not None else "", styles["Normal"])
                for c in r
            ])

        if not col_widths:
            total = 180 * mm
            w = total / len(headers)
            col_widths = [w] * len(headers)

        table = Table(data, colWidths=col_widths, repeatRows=1)
        table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), GOLD),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
            ("FONTSIZE", (0, 0), (-1, -1), 8),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("TOPPADDING", (0, 0), (-1, -1), 4),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
            ("LEFTPADDING", (0, 0), (-1, -1), 5),
            ("RIGHTPADDING", (0, 0), (-1, -1), 5),
            ("LINEBELOW", (0, 0), (-1, 0), 0.8, CHARCOAL),
            ("LINEBELOW", (0, 1), (-1, -1), 0.3, BORDER),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, BG]),
        ]))
        story.append(table)

    doc.build(story, onFirstPage=_footer, onLaterPages=_footer)
    buf.seek(0)
    return buf